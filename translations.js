const applyTranslation = (lang) => {
    document.documentElement.lang = lang;
    document.title = translations[lang].seo.title;
    document.querySelector('meta[name="description"]').content = translations[lang].seo.description;
    document.querySelector('meta[property="og:title"]').content = translations[lang].seo.title;
    document.querySelector('meta[property="og:description"]').content = translations[lang].seo.description;
    document.querySelectorAll('.lang-btn').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.lang === lang)));

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.getAttribute('data-i18n');
        if (!key) return;

        const parts = key.split('.');
        let text = translations[lang];
        for (const part of parts) {
            if (!text || typeof text !== 'object') {
                text = null;
                break;
            }
            text = text[part];
        }

        if (typeof text === 'string') {
            if (element.matches('button[type="submit"]') && element.disabled) {
                element.textContent = translations[lang].quote.submitSending;
            } else element.textContent = text;
        }
    });

    document.querySelectorAll('[data-i18n-alt]').forEach(element => {
        const text = element.dataset.i18nAlt.split('.').reduce((value, key) => value?.[key], translations[lang]);
        if (typeof text === 'string') element.alt = text;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (!key) return;

        const parts = key.split('.');
        let text = translations[lang];
        for (const part of parts) {
            if (!text || typeof text !== 'object') {
                text = null;
                break;
            }
            text = text[part];
        }

        if (typeof text === 'string') {
            element.setAttribute('placeholder', text);
        }
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
        const key = element.getAttribute('data-i18n-aria-label');
        if (!key) return;

        const parts = key.split('.');
        let text = translations[lang];
        for (const part of parts) {
            if (!text || typeof text !== 'object') {
                text = null;
                break;
            }
            text = text[part];
        }

        if (typeof text === 'string') {
            element.setAttribute('aria-label', text);
        }
    });
};

const setActiveLanguage = (lang) => {
    document.querySelectorAll('.lang-btn').forEach((btn) => {
        btn.classList.toggle('active-lang', btn.getAttribute('data-lang') === lang);
    });
};

const getTranslation = (key, fallback = '') => {
    const lang = window.currentLanguage || document.documentElement.lang || 'de';
    const parts = key.split('.');
    let text = translations[lang];

    for (const part of parts) {
        if (!text || typeof text !== 'object') {
            return fallback;
        }
        text = text[part];
    }

    return typeof text === 'string' ? text : fallback;
};

window.getTranslation = getTranslation;
window.currentLanguage = 'de';

window.addEventListener('DOMContentLoaded', () => {
    const requested = new URLSearchParams(location.search).get('lang');
    const defaultLang = Object.hasOwn(translations, requested) ? requested : 'de';
    window.currentLanguage = defaultLang;
    applyTranslation(defaultLang);
    setActiveLanguage(defaultLang);

    document.querySelectorAll('.lang-btn').forEach((button) => {
        button.addEventListener('click', () => {
            const lang = button.getAttribute('data-lang');
            if (lang && Object.hasOwn(translations, lang)) {
                window.currentLanguage = lang;
                applyTranslation(lang);
                setActiveLanguage(lang);
                document.dispatchEvent(new CustomEvent('languagechange'));
                const url = new URL(location.href);
                url.searchParams.set('lang', lang);
                try { history.replaceState(null, '', url); } catch { /* Local file previews may restrict history. */ }
            }
        });
    });
});
