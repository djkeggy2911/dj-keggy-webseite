const applyTranslation = (lang) => {
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.getAttribute('data-i18n');
        if (!key) return;

        const parts = key.split('.');
        let text = translations[lang];
        for (const part of parts) {
            if (!text || typeof text !== 'object') {
                text = null;
                break;
            }
            text = text[part];
        }

        if (typeof text === 'string') {
            element.textContent = text;
        }
    });
};

const setActiveLanguage = (lang) => {
    document.querySelectorAll('.lang-btn').forEach((btn) => {
        btn.classList.toggle('active-lang', btn.getAttribute('data-lang') === lang);
    });
};

const getTranslation = (key, fallback = '') => {
    const lang = window.currentLanguage || document.documentElement.lang || 'de';
    const parts = key.split('.');
    let text = translations[lang];

    for (const part of parts) {
        if (!text || typeof text !== 'object') {
            return fallback;
        }
        text = text[part];
    }

    return typeof text === 'string' ? text : fallback;
};

window.getTranslation = getTranslation;
window.currentLanguage = 'hr';

window.addEventListener('DOMContentLoaded', () => {
    const defaultLang = 'hr';
    window.currentLanguage = defaultLang;
    applyTranslation(defaultLang);
    setActiveLanguage(defaultLang);

    document.querySelectorAll('.lang-btn').forEach((button) => {
        button.addEventListener('click', () => {
            const lang = button.getAttribute('data-lang');
            if (lang && translations[lang]) {
                window.currentLanguage = lang;
                applyTranslation(lang);
                setActiveLanguage(lang);
            }
        });
    });
});
